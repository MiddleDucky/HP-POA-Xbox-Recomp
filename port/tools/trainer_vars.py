#!/usr/bin/env python3
"""Writes port/src/trainer_vars.h: every tuning variable PoA registers at start, for the trainer (F11).

The title's static constructors each build one variable object (__thiscall, ecx = the object) with a name, a group
mask, the address of the value the game reads and its range:

  sub_001A62D0  bool   (name, group, &value, default, 0)
  sub_001A63C0  float  (name, group, &value, default, scale, min, max, 0)   value = default * scale
  sub_001A64B0  int    (name, group, &value, default, min, max, 0)
  sub_001A6550  uint   (name, group, &value, default, min, max, 0)

They are read here from the recompiled constructors (each a short run of pushes, then the call) and the names from
the XBE. Run after regen.sh:  python3 port/tools/trainer_vars.py <default.xbe> [port/src/recomp/gen]
"""
import glob, os, re, struct, sys

KINDS = {'001A62D0': ('TV_BOOL', 5), '001A63C0': ('TV_FLOAT', 8), '001A64B0': ('TV_INT', 7), '001A6550': ('TV_UINT', 7)}


def xbe_strings(path):
    xbe = open(path, 'rb').read()
    base = struct.unpack_from('<I', xbe, 0x104)[0]
    nsec = struct.unpack_from('<I', xbe, 0x11C)[0]
    sh = struct.unpack_from('<I', xbe, 0x120)[0] - base
    secs = [struct.unpack_from('<6I', xbe, sh + i * 56)[1:5] for i in range(nsec)]

    def string(va):
        for sva, vs, ra, rs in secs:
            if sva <= va < sva + rs:
                o = ra + va - sva
                end = xbe.index(b'\0', o)
                s = xbe[o:end]
                return s.decode() if s and all(32 <= c < 127 for c in s) else None
        return None
    return string


def as_float(v):
    return struct.unpack('<f', struct.pack('<I', v))[0]


def main():
    string = xbe_strings(sys.argv[1])
    here = os.path.dirname(os.path.abspath(__file__))
    gen = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', 'src', 'recomp', 'gen')
    rows = []
    for f in sorted(glob.glob(os.path.join(gen, 'recomp_*.c'))):
        lines = open(f).read().split('\n')
        for i, line in enumerate(lines):
            m = re.search(r'RECOMP_ABI_CALL\(0x([0-9A-F]+)u', line)
            if not m or m.group(1) not in KINDS:
                continue
            kind, nargs = KINDS[m.group(1)]
            pushes, obj = [], None
            for j in range(i - 1, max(0, i - 14), -1):
                if 'RECOMP_ABI_CALL' in lines[j] or (lines[j].startswith('loc_') and pushes and len(pushes) >= nargs):
                    break
                mm = re.match(r'\s*ecx = 0x([0-9A-F]+);', lines[j])
                if mm and obj is None:
                    obj = int(mm.group(1), 16)
                mm = re.match(r'\s*PUSH32\(esp, (0x[0-9A-F]+|\d+)u?\);', lines[j])
                if mm:
                    pushes.append(int(mm.group(1), 0))
            if obj is None or len(pushes) != nargs:
                continue
            a = pushes  # last pushed first: a[0] is the first argument
            name = string(a[0])
            if not name:
                continue
            if kind == 'TV_FLOAT':
                scale = as_float(a[4]) or 1.0
                rows.append((name, kind, a[1], a[2], as_float(a[3]), as_float(a[5]), as_float(a[6]), scale))
            elif kind == 'TV_BOOL':
                rows.append((name, kind, a[1], a[2], float(a[3]), 0.0, 1.0, 1.0))
            elif kind == 'TV_INT':
                s = lambda v: struct.unpack('<i', struct.pack('<I', v))[0]
                rows.append((name, kind, a[1], a[2], float(s(a[3])), float(s(a[4])), float(s(a[5])), 1.0))
            else:
                rows.append((name, kind, a[1], a[2], float(a[3]), float(a[4]), float(a[5]), 1.0))
    seen, out = set(), []
    for r in rows:
        if r[3] not in seen:
            seen.add(r[3])
            out.append(r)

    def num(v):
        if v != v or abs(v) > 3.0e38:
            return '3.4e38f' if v > 0 else '-3.4e38f'
        return repr(float(v)) + 'f'
    dst = os.path.join(here, '..', 'src', 'trainer_vars.h')
    with open(dst, 'w') as w:
        w.write('/* Generated by port/tools/trainer_vars.py from the recompiled constructors: PoA\'s tuning variables\n'
                ' * (name, kind, group mask, guest address of the value, default, min, max, float scale). */\n')
        for r in out:
            w.write('{"%s", %s, 0x%Xu, 0x%Xu, %s, %s, %s, %s},\n' % (r[0], r[1], r[2], r[3], num(r[4]), num(r[5]),
                                                                      num(r[6]), num(r[7])))
    print('%d variables -> %s' % (len(out), dst))


if __name__ == '__main__':
    main()
